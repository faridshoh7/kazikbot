def default_text(key: str) -> str:
    return SECTIONS[key][2]


def raw_text(key: str) -> str:
    """Текст как есть, вместе со вставками — его показываем админу."""
    saved = get_setting(f"text_{key}")
    return saved if saved else default_text(key)


def set_text(key: str, value: str):
    set_setting(f"text_{key}", value)


def reset_text(key: str):
    set_setting(f"text_{key}", "")


def render(key: str, **values) -> str:
    """Готовый текст для игрока: подставляет вставки простой заменой."""
    text = raw_text(key)
    for name, value in values.items():
        text = text.replace("{" + name + "}", str(value))
    return text
